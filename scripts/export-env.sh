#!/usr/bin/env bash
# Pulls every live secret/connection-string this deployment produced out of
# Azure (via `az`) and writes them into the root .env file. Safe to re-run --
# it always reflects the current state of the resource group.
#
# Requires: az cli logged in, jq NOT required (uses --query/-o tsv), and
# .secrets/postgres_admin_password.txt + .secrets/unique_suffix.txt from the
# provisioning step (see docs/SETUP.md).
set -euo pipefail

RG="dhara-platform-rg"
ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

PG_PASSWORD=$(cat .secrets/postgres_admin_password.txt)
SUFFIX=$(cat .secrets/unique_suffix.txt)

echo "Reading deployment outputs..."
OUT=$(az deployment group show -g "$RG" -n main --query properties.outputs -o json)

get() { echo "$OUT" | python -c "import json,sys; print(json.load(sys.stdin).get('$1',{}).get('value',''))"; }

POSTGRES_FQDN=$(get postgresFqdn)
POSTGRES_DB=$(get postgresDatabaseName)
IOT_HUB_NAME=$(get iotHubName)
STORAGE_ACCOUNT=$(get storageAccountName)
COMMUNICATION_NAME=$(get communicationServiceName)
SPEECH_NAME=$(get speechAccountName)
SPEECH_REGION=$(get speechRegion)
OPENAI_ENDPOINT=$(get openAiEndpoint)
OPENAI_ACCOUNT=$(get openAiAccountName)
KEY_VAULT_NAME=$(get keyVaultName)
APPI_CONNSTR=$(get appInsightsConnectionString)
API_URL=$(get apiUrl)
ADVISORY_URL=$(get advisoryBotUrl)
SWA_HOST=$(get staticWebAppDefaultHostname)

echo "Fetching IoT Hub keys..."
IOTHUB_CONNSTR=$(az iot hub connection-string show -n "$IOT_HUB_NAME" --policy-name iothubowner -o tsv --query connectionString)
IOTHUB_EVENTHUB_ENDPOINT=$(az iot hub show -n "$IOT_HUB_NAME" --query "properties.eventHubEndpoints.events.endpoint" -o tsv)
IOTHUB_EVENTHUB_PATH=$(az iot hub show -n "$IOT_HUB_NAME" --query "properties.eventHubEndpoints.events.path" -o tsv)
IOTHUB_KEY=$(az iot hub policy show --hub-name "$IOT_HUB_NAME" --name iothubowner --query primaryKey -o tsv)
IOTHUB_EVENTHUB_COMPATIBLE="Endpoint=${IOTHUB_EVENTHUB_ENDPOINT};SharedAccessKeyName=iothubowner;SharedAccessKey=${IOTHUB_KEY};EntityPath=${IOTHUB_EVENTHUB_PATH}"

echo "Fetching Storage key..."
STORAGE_CONNSTR=$(az storage account show-connection-string -n "$STORAGE_ACCOUNT" -g "$RG" -o tsv --query connectionString)

echo "Fetching Communication Services key..."
ACS_CONNSTR=$(az communication list-key -n "$COMMUNICATION_NAME" -g "$RG" --query primaryConnectionString -o tsv)

echo "Fetching Speech key..."
SPEECH_KEY=$(az cognitiveservices account keys list -n "$SPEECH_NAME" -g "$RG" --query key1 -o tsv)

echo "Fetching OpenAI/AIServices key..."
OPENAI_KEY=""
if [ -n "$OPENAI_ACCOUNT" ]; then
  OPENAI_KEY=$(az cognitiveservices account keys list -n "$OPENAI_ACCOUNT" -g "$RG" --query key1 -o tsv)
fi

echo "Writing .env..."
cat > .env <<EOF
# Auto-generated by scripts/export-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Do not commit this file. See docs/azure-requirements.md for what each value is and how to rotate it.

ENVIRONMENT=production
LOG_LEVEL=INFO

DATABASE_URL=postgresql+psycopg://dhara_admin:${PG_PASSWORD}@${POSTGRES_FQDN}:5432/${POSTGRES_DB}?sslmode=require

IOT_HUB_CONNECTION_STRING=${IOTHUB_CONNSTR}
IOT_HUB_EVENTHUB_COMPATIBLE_ENDPOINT=${IOTHUB_EVENTHUB_COMPATIBLE}
IOT_HUB_EVENTHUB_CONSUMER_GROUP=\$Default
IOT_HUB_NAME=${IOT_HUB_NAME}

STORAGE_ACCOUNT_CONNECTION_STRING=${STORAGE_CONNSTR}
STORAGE_CONTAINER_PHOTOS=advisory-photos
STORAGE_CONTAINER_FIRMWARE=firmware

KEY_VAULT_URI=https://${KEY_VAULT_NAME}.vault.azure.net/

ACS_CONNECTION_STRING=${ACS_CONNSTR}
ACS_WHATSAPP_CHANNEL_REGISTRATION_ID=
ACS_SENDER_PHONE_NUMBER=

AZURE_OPENAI_ENDPOINT=${OPENAI_ENDPOINT}
AZURE_OPENAI_API_KEY=${OPENAI_KEY}
AZURE_OPENAI_DEPLOYMENT=dhara-advisory-gpt
AZURE_OPENAI_API_VERSION=2024-10-21

SPEECH_KEY=${SPEECH_KEY}
SPEECH_REGION=${SPEECH_REGION}

API_SHARED_SECRET=$(cat .secrets/api_shared_secret.txt)
ENTRA_TENANT_ID=$(az account show --query tenantId -o tsv)
ENTRA_API_CLIENT_ID=$(cat .secrets/entra_app_id.txt 2>/dev/null || echo "")

APPLICATIONINSIGHTS_CONNECTION_STRING=${APPI_CONNSTR}

API_BASE_URL=${API_URL}
ADVISORY_BOT_URL=${ADVISORY_URL}
ADVISORY_BOT_PUBLIC_URL=${ADVISORY_URL}

CONTROL_LOOP_INTERVAL_MINUTES=15
SEASONAL_VOLUMETRIC_CAP_M3_PER_HA=6500
ADVISORY_CONFIDENCE_THRESHOLD=0.72

SIMULATOR_TICK_SECONDS=60

STATIC_WEB_APP_HOSTNAME=${SWA_HOST}
EOF

echo "Wrote $ROOT_DIR/.env"
